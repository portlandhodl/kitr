//! Direct OpenSSL FFI for the primitives used by kitty remote control.
//!
//! This is a port of `kitty/crypto.c`:
//!
//! * X25519 key generation, raw public/private keys and ECDH derivation.
//!   `crypto.c` only implements X25519 (`EVP_PKEY_X25519`); it does *not*
//!   implement P-256, despite what the porting brief said.
//! * SHA-1/224/256/384/512 hashing of the raw shared secret. Kitty's
//!   `derive_secret()` defaults to SHA-256, producing a 32-byte `Secret`.
//! * AES-256-GCM with a 12-byte random IV and a 16-byte authentication tag,
//!   including the incremental AAD/update/finish state machine used by
//!   `AES256GCMEncrypt` and `AES256GCMDecrypt`.
//!
//! No third-party Rust crates are used. OpenSSL is linked directly. Secrets
//! are zeroized with `OPENSSL_cleanse` on drop. Unlike the C implementation we
//! do not `mlock()` secret memory (the C code does not check `mlock()` for the
//! `Secret` type either on all paths); see the crate report for details.

use crate::error::{Error, Result};
use std::ffi::CStr;
use std::os::raw::{c_char, c_int, c_uint, c_ulong, c_void};
use std::ptr;

const EVP_PKEY_X25519: c_int = 1034;
const EVP_CTRL_AEAD_SET_IVLEN: c_int = 0x9;
const EVP_CTRL_AEAD_GET_TAG: c_int = 0x10;
const EVP_CTRL_AEAD_SET_TAG: c_int = 0x11;

/// Length of an X25519 raw public/private key.
pub const X25519_KEY_LEN: usize = 32;
/// AES-256 key length.
pub const AES_KEY_LEN: usize = 32;
/// AES-GCM IV length generated by kitty.
pub const GCM_IV_LEN: usize = 12;
/// AES-GCM tag length generated by kitty.
pub const GCM_TAG_LEN: usize = 16;

