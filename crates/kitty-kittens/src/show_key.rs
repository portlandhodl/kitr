//! Show-key kitten, ported from `kittens/show_key`.
//!
//! Legacy mode displays the bytes produced by the terminal in `caret` form
//! and as a `send_text` escape string. Kitty mode decodes CSI-u key events and
//! displays the modifiers, event type, associated text and the full CSI.

use std::io::{self, Write};
use std::time::Duration;

use crate::tui::Tty;

pub const SHOW_KEY_USAGE: &str = "\
Usage: kitten show_key [options]

Show the codes generated by the terminal for key presses.

Options:
  -m, --key-mode normal|application|kitty|unchanged
  -h, --help";

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum KeyMode {
    #[default]
    Normal,
    Application,
    Kitty,
    Unchanged,
}

impl KeyMode {
    pub fn parse(value: &str) -> Option<Self> {
        Some(match value {
            "normal" => Self::Normal,
            "application" => Self::Application,
            "kitty" => Self::Kitty,
            "unchanged" => Self::Unchanged,
            _ => return None,
        })
    }
}

#[derive(Clone, Debug, Default)]
pub struct ShowKeyOptions {
    pub key_mode: KeyMode,
    pub help: bool,
}

pub fn parse_show_key_args(args: &[String]) -> Result<ShowKeyOptions, String> {
    let mut opts = ShowKeyOptions::default();
    let mut index = 0usize;
    while index < args.len() {
        let arg = &args[index];
        let (name, inline) = arg
            .split_once('=')
            .map_or((arg.as_str(), None), |(a, b)| (a, Some(b.to_owned())));
        let mut take = || -> String {
            if let Some(value) = inline.clone() {
                return value;
            }
            index += 1;
            args.get(index).cloned().unwrap_or_default()
        };
        match name {
            "-h" | "--help" => opts.help = true,
            "-m" | "--key-mode" => {
                let value = take();
                opts.key_mode =
                    KeyMode::parse(&value).ok_or_else(|| format!("invalid key mode: {value}"))?;
            }
            other => return Err(format!("unknown option: {other}")),
        }
        index += 1;
    }
    Ok(opts)
}

/// Render legacy terminal input in the two columns used by the kitten.
pub fn legacy_key_display(input: &[u8]) -> (String, String) {
    let ctrl_keys = b"@ABCDEFGHIJKLMNOPQRSTUVWXYZ[\\]^_";
    let mut unix = String::new();
    let mut send_text = String::new();
    for byte in input {
        if (*byte as usize) < ctrl_keys.len() {
            unix.push('^');
            unix.push(ctrl_keys[*byte as usize] as char);
        } else if *byte == 127 {
            unix.push_str("^?");
        } else {
            unix.push(*byte as char);
        }
    }
    for ch in String::from_utf8_lossy(input).chars() {
        send_text.push_str(&escape_char_for_send_text(ch));
    }
    (unix, send_text)
}

fn escape_char_for_send_text(ch: char) -> String {
    match ch {
        '\\' => "\\\\".to_owned(),
        '\n' => "\\n".to_owned(),
        '\r' => "\\r".to_owned(),
        '\t' => "\\t".to_owned(),
        '\'' => "\\'".to_owned(),
        ch if ch.is_control() => format!("\\x{:02x}", ch as u32),
        ch => ch.to_string(),
    }
}

/// A decoded kitty keyboard-protocol event.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct KittyKeyEvent {
    pub key: String,
    pub mods: Vec<String>,
    pub event_type: String,
    pub text: String,
    pub csi: String,
    pub shifted_key: String,
    pub alternate_key: String,
}

impl KittyKeyEvent {
    pub fn key_with_mods(&self) -> String {
        if self.mods.is_empty() {
            self.key.clone()
        } else {
            format!("{}+{}", self.mods.join("+"), self.key)
        }
    }
}

/// Format a CSI sequence with spaces around sub-parameters and the final byte,
/// matching `csi()` in the Go kitten.
pub fn csi_display(csi: &str) -> String {
    let body = csi.strip_prefix("CSI ").unwrap_or(csi);
    if body.len() < 2 {
        return csi.to_owned();
    }
    let final_byte = body.chars().last().unwrap_or(' ');
    let rest = &body[..body.len() - final_byte.len_utf8()];
    let spaced = rest.replace(':', " : ").replace(';', " ; ");
    format!("CSI {spaced} {final_byte}")
}

pub fn modifiers_from_value(value: u32) -> Vec<String> {
    let bits = value.saturating_sub(1);
    let mut out = Vec::new();
    for (bit, name) in [
        (1, "shift"),
        (2, "alt"),
        (4, "ctrl"),
        (8, "super"),
        (16, "hyper"),
        (32, "meta"),
        (64, "caps_lock"),
        (128, "num_lock"),
    ] {
        if bits & bit != 0 {
            out.push(name.to_owned());
        }
    }
    out
}

/// Parse one kitty CSI-u sequence. `body` is the part between `CSI` and `u`.
pub fn parse_csi_u(body: &str) -> Option<KittyKeyEvent> {
    let mut fields = body.split(';');
    let key_field = fields.next().unwrap_or("");
    let mods_field = fields.next().unwrap_or("1");
    let text_field = fields.next().unwrap_or("");
    let (code, shifted, base) = if key_field.contains(':') {
        let mut parts = key_field.split(':');
        let code = parts.next().unwrap_or("0");
        let shifted = parts.next().unwrap_or("");
        let base = parts.next().unwrap_or("");
        (code, shifted, base)
    } else {
        (key_field, "", "")
    };
    let code = code.parse::<u32>().ok()?;
    let (mods_value, event_value) = mods_field
        .split_once(':')
        .map_or((mods_field, "1"), |(m, e)| (m, e));
    let mods_value = mods_value.parse::<u32>().unwrap_or(1);
    let event = match event_value.parse::<u32>().unwrap_or(1) {
        2 => "repeat",
        3 => "release",
        _ => "press",
    };
    let key = key_name(code);
    let text = text_field
        .split(':')
        .map(|part| {
            u32::from_str_radix(part, 16)
                .ok()
                .and_then(char::from_u32)
                .map(String::from)
                .unwrap_or_default()
        })
        .collect::<Vec<_>>()
        .join("");
    Some(KittyKeyEvent {
        key,
        mods: modifiers_from_value(mods_value),
        event_type: event.to_owned(),
        text,
        csi: format!("CSI {body}u"),
        shifted_key: u32::from_str_radix(shifted, 16)
            .ok()
            .and_then(char::from_u32)
            .map(String::from)
            .unwrap_or_default(),
        alternate_key: u32::from_str_radix(base, 16)
            .ok()
            .and_then(char::from_u32)
            .map(String::from)
            .unwrap_or_default(),
    })
}

fn key_name(code: u32) -> String {
    let name = match code {
        0 => "space".to_owned(),
        13 => "enter".to_owned(),
        27 => "escape".to_owned(),
        127 => "backspace".to_owned(),
        9 => "tab".to_owned(),
        _ => char::from_u32(code)
            .map(|ch| ch.to_string())
            .unwrap_or_else(|| format!("u+{code:x}")),
    };
    if code == b' ' as u32 {
        "space".to_owned()
    } else {
        name
    }
}

/// Decode all complete kitty CSI-u events from a byte buffer.
pub fn parse_kitty_events(input: &[u8]) -> Vec<KittyKeyEvent> {
    let mut out = Vec::new();
    let text = String::from_utf8_lossy(input);
    let bytes = text.as_bytes();
    let mut i = 0usize;
    while i + 2 < bytes.len() {
        if bytes[i] == 0x1b && bytes[i + 1] == b'[' {
            if let Some(end) = bytes[i + 2..].iter().position(|b| *b == b'u') {
                let body = &text[i + 2..i + 2 + end];
                if let Some(event) = parse_csi_u(body) {
                    out.push(event);
                }
                i = i + 2 + end + 1;
                continue;
            }
        }
        i += 1;
    }
    out
}

/// Run the legacy show-key loop.
pub fn run_legacy_ui(
    tty: &mut dyn Tty,
    opts: &ShowKeyOptions,
    out: &mut dyn Write,
) -> io::Result<()> {
    if opts.key_mode != KeyMode::Unchanged {
        let mode = if opts.key_mode == KeyMode::Application {
            "\x1b[?1h"
        } else {
            "\x1b[?1l"
        };
        tty.write_all(mode.as_bytes())?;
    }
    writeln!(out, "Press any keys - Ctrl+D will terminate this program")?;
    writeln!(out, "UNIX\t\tsend_text")?;
    let mut buf = [0u8; 64];
    loop {
        let n = match tty.read(&mut buf, Duration::from_secs(1)) {
            Ok(0) => break,
            Ok(n) => n,
            Err(err) if err.kind() == io::ErrorKind::TimedOut => continue,
            Err(err) => return Err(err),
        };
        let (unix, send_text) = legacy_key_display(&buf[..n]);
        writeln!(out, "{unix}\t\t{send_text}")?;
        if n == 1 && buf[0] == 4 {
            break;
        }
    }
    if opts.key_mode != KeyMode::Unchanged {
        tty.write_all(b"\x1b[?1l")?;
    }
    tty.flush()
}

/// Run the kitty-protocol show-key loop.
pub fn run_kitty_ui(tty: &mut dyn Tty, out: &mut dyn Write) -> io::Result<()> {
    tty.write_all(b"\x1b[>1u\x1b[?25l")?;
    writeln!(out, "Press any keys - Ctrl+C or Ctrl+D will terminate")?;
    let mut buf = [0u8; 256];
    let mut pending = Vec::new();
    loop {
        let n = match tty.read(&mut buf, Duration::from_secs(1)) {
            Ok(0) => break,
            Ok(n) => n,
            Err(err) if err.kind() == io::ErrorKind::TimedOut => continue,
            Err(err) => return Err(err),
        };
        let quit = buf[..n].contains(&3) || buf[..n].contains(&4);
        pending.extend_from_slice(&buf[..n]);
        let events = parse_kitty_events(&pending);
        if !events.is_empty() {
            for event in &events {
                print_kitty_event(out, event)?;
            }
            pending.clear();
        }
        if quit {
            break;
        }
    }
    tty.write_all(b"\x1b[<u\x1b[?25h")?;
    tty.flush()
}

fn print_kitty_event(out: &mut dyn Write, event: &KittyKeyEvent) -> io::Result<()> {
    let key = if event.key == " " {
        "space".to_owned()
    } else {
        event.key.clone()
    };
    let display_key = if event.mods.is_empty() {
        key
    } else {
        format!("{}+{}", event.mods.join("+"), key)
    };
    writeln!(out, "{} {} {}", display_key, event.event_type, event.text)?;
    writeln!(out, "{}", csi_display(&event.csi))?;
    if !event.shifted_key.is_empty() {
        write!(out, "Shifted key: {} ", event.shifted_key)?;
    }
    if !event.alternate_key.is_empty() {
        write!(out, "Alternate key: {} ", event.alternate_key)?;
    }
    if !event.shifted_key.is_empty() || !event.alternate_key.is_empty() {
        writeln!(out)?;
    }
    writeln!(out)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::tui::FakeTty;

    #[test]
    fn legacy_display() {
        let (unix, send) = legacy_key_display(b"\x01\x1b\x7fA");
        assert_eq!(unix, "^A^[^?A");
        assert_eq!(send, "\\x01\\x1b\\x7fA");
    }

    #[test]
    fn csi_u_decoding_and_display() {
        let event = parse_csi_u("97;5:1;61").unwrap();
        assert_eq!(event.key, "a");
        assert_eq!(event.mods, vec!["ctrl"]);
        assert_eq!(event.event_type, "press");
        assert_eq!(event.text, "a");
        assert_eq!(csi_display(&event.csi), "CSI 97 ; 5 : 1 ; 61 u");
        let events = parse_kitty_events(b"\x1b[97;5u\x1b[13u");
        assert_eq!(events.len(), 2);
        assert_eq!(events[1].key, "enter");
    }

    #[test]
    fn kitty_ui_reports_keys() {
        let mut tty = FakeTty::new(80, 24, b"\x1b[97;5;61u\x03");
        let mut out = Vec::new();
        run_kitty_ui(&mut tty, &mut out).unwrap();
        let text = String::from_utf8_lossy(&out);
        assert!(text.contains("ctrl+a press a"), "{text}");
        assert!(text.contains("CSI 97 ; 5 ; 61 u"), "{text}");
        assert!(tty.output_text().contains(">1u"));
    }

    #[test]
    fn legacy_ui_reads_until_eof() {
        let mut tty = FakeTty::new(80, 24, b"a\x04");
        let mut out = Vec::new();
        run_legacy_ui(&mut tty, &ShowKeyOptions::default(), &mut out).unwrap();
        let text = String::from_utf8_lossy(&out);
        assert!(text.contains("a^D"), "{text}");
    }
}
